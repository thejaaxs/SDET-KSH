// Relational & Comparision Operator

// > More than !
// < Less than !
// >= More than equal !
// <= Less than equal !

var result = 10 > 5
console.log(result)

var result2 = 10 < 5
console.log(result2)

var result3 = 10 <= 10
console.log(result3)

var result4 = 20 >= 20
console.log(result4)

var x = 10;
console.log(x == '10') // This gives true since it compares the value and is a lose comparision !
console.log(x === '10') // This is a strict comparision and compares the data as well !
// But this works if : x == 10
console.log(x === 10)